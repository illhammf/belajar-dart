
void main() {
  int angka = 1;

  print('==============================');
  print('         WHILE LOOP');
  print('==============================');

  while (angka <= 5) {
    print('Angka ke-$angka');

    angka++; // artinya jika angka = angka + 1, maka nilai angka akan bertambah 1 setiap perulangan
  }

  print('==============================');
  print('Perulangan selesai!');
}
